/* ============================================================================
   reads.js: animates "What a session reads, and when" (#concept) on scroll.

   The ring itself is GENERATED by scripts/data-model.py from
   docs/data-model.yaml and must not be edited by hand. This script only reads
   the generated SVG and lays the order of reading over it, from the centre
   outwards, as the figure scrolls through the viewport:
     1  the session starts (centre)
     2  what every session reads before its first answer (inner ring)
     3  families of which something is read at session start (filled dots)
     4  families opened when the work names them (hollow dots)
     5  the references walked along (the track ring)
     6  outside git: secret and object stores by URI (dashed boundary)
   The step list above the figure and the legend inside it follow along.
   Reduced motion: nothing moves, the figure stays as generated.
   ============================================================================ */
(function () {
  "use strict";
  var svg = document.querySelector('#concept svg[viewBox="0 0 800 856"]');
  var steps = [].slice.call(document.querySelectorAll("#reads-steps li"));
  if (!svg) return;
  if (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  var NS = "http://www.w3.org/2000/svg", C = 400;
  var clamp = function (a, b, v) { return v < a ? a : v > b ? b : v; };
  var out3 = function (k) { return 1 - Math.pow(1 - k, 3); };
  var seg = function (p, a, b) { return clamp(0, 1, (p - a) / (b - a)); };
  var num = function (el, a) { return parseFloat(el.getAttribute(a)); };
  var mk = function (tag, attrs, before) { var e = document.createElementNS(NS, tag); for (var k in attrs) e.setAttribute(k, attrs[k]); svg.insertBefore(e, before || null); return e; };

  /* read the generated drawing */
  var centre = svg.querySelector("circle.dg-merge");
  var centreLbl = [].slice.call(svg.querySelectorAll("text.dg-lbl")).filter(function (t) { return Math.abs(num(t, "y") - 405) < 2; });
  var inner = [].slice.call(svg.querySelectorAll("text.dg-mono")).filter(function (t) { return Math.hypot(num(t, "x") - C, num(t, "y") - C) < 182; });
  var dots = [].slice.call(svg.querySelectorAll("circle")).filter(function (c) { return c.getAttribute("r") === "5" && num(c, "cy") < 780; })
    .map(function (c) {
      var lbl = c.nextElementSibling && c.nextElementSibling.classList.contains("dg-sub") ? c.nextElementSibling : null;
      var x = num(c, "cx"), y = num(c, "cy");
      return { c: c, lbl: lbl, x: x, y: y, filled: c.getAttribute("fill") === "var(--accent)", ang: Math.atan2(y - C, x - C) };
    });
  var filled = dots.filter(function (d) { return d.filled; });
  var hollow = dots.filter(function (d) { return !d.filled; }).sort(function (a, b) { return ((a.ang + 2.2) % 6.283) - ((b.ang + 2.2) % 6.283); });
  var track = [].slice.call(svg.querySelectorAll("circle.dg-track")).filter(function (c) { return c.getAttribute("r") === "330"; })[0];
  var bound = [].slice.call(svg.querySelectorAll("circle.dg-bound")).filter(function (c) { return c.getAttribute("r") === "372"; })[0];
  var legendDots = [].slice.call(svg.querySelectorAll("circle")).filter(function (c) { return num(c, "cy") >= 780; });
  var legendTxt = [].slice.call(svg.querySelectorAll("text.dg-cap")).filter(function (t) { return num(t, "y") >= 780; });
  if (!centre || !inner.length || !dots.length) return;

  /* overlays: read lines, sparks, a comet on the reference track */
  var first = svg.firstElementChild;
  var lines = dots.map(function (d) {
    var a = Math.atan2(d.y - C, d.x - C), x0 = C + Math.cos(a) * 48, y0 = C + Math.sin(a) * 48;
    var len = Math.hypot(d.x - x0, d.y - y0) - 6;
    var l = mk("line", { x1: x0, y1: y0, x2: x0 + Math.cos(a) * len, y2: y0 + Math.sin(a) * len,
      stroke: "var(--accent)", "stroke-width": d.filled ? 1.4 : 1, "stroke-dasharray": d.filled ? len + " " + len : "3 4", opacity: 0 }, first);
    l.__len = len; return l;
  });
  var sparks = inner.map(function () { return mk("circle", { r: 3.5, fill: "var(--accent)", opacity: 0 }); });
  var comet = track ? mk("circle", { cx: C, cy: C, r: 330, fill: "none", stroke: "var(--accent)", "stroke-width": 2.4, "stroke-linecap": "round",
    "stroke-dasharray": "90 2100", opacity: 0, transform: "rotate(-90 400 400)" }) : null;

  function set(el, o) { if (el) el.style.opacity = o.toFixed(3); }
  function legend(i, on) { set(legendDots[i], on ? 1 : .35); set(legendTxt[i], on ? 1 : .45); }

  function draw(p) {
    // 1 centre
    var k1 = out3(seg(p, 0, .1)), s = .6 + .4 * k1;
    centre.setAttribute("transform", "translate(400 400) scale(" + s.toFixed(3) + ") translate(-400 -400)");
    set(centre, .25 + .75 * k1); centreLbl.forEach(function (t) { set(t, k1); });
    // 2 inner ring, one by one, each sends a spark to the centre
    inner.forEach(function (t, i) {
      var k = seg(p, .1 + i * .022, .1 + i * .022 + .07);
      set(t, .15 + .85 * out3(k));
      var sp = sparks[i], x = num(t, "x"), y = num(t, "y") - 4;
      sp.setAttribute("cx", (x + (C - x) * k).toFixed(1)); sp.setAttribute("cy", (y + (C - y) * k).toFixed(1));
      set(sp, k > 0 && k < 1 ? Math.sin(Math.PI * k) : 0);
    });
    // 3 filled dots: a line from the centre, then the family lights up
    filled.forEach(function (d, i) {
      var k = seg(p, .34 + i * .025, .34 + i * .025 + .08), l = lines[dots.indexOf(d)];
      l.setAttribute("stroke-dashoffset", (l.__len * (1 - out3(k))).toFixed(1)); set(l, k > 0 ? .9 : 0);
      set(d.c, .2 + .8 * out3(k)); set(d.lbl, .25 + .75 * out3(k));
    });
    // 4 hollow dots: opened one by one when the work names them
    hollow.forEach(function (d, i) {
      var a = .54 + i * (.22 / hollow.length), k = seg(p, a, a + .04), l = lines[dots.indexOf(d)];
      set(l, Math.sin(Math.PI * k) * .7);
      set(d.c, .2 + .8 * out3(k)); set(d.lbl, .25 + .75 * out3(k));
    });
    // 5 references: the track brightens, a comet runs along it
    var k5 = seg(p, .78, .9);
    set(track, .3 + .7 * k5);
    if (comet) { comet.setAttribute("stroke-dashoffset", (-p * 3600).toFixed(1)); set(comet, Math.sin(Math.PI * k5) * .9); }
    // 6 outside git
    var k6 = seg(p, .9, .98);
    set(bound, .25 + .75 * k6);
    if (bound) bound.style.strokeDashoffset = (-p * 60).toFixed(1);

    var phase = p < .1 ? 0 : p < .34 ? 1 : p < .54 ? 2 : p < .78 ? 3 : p < .9 ? 4 : 5;
    legend(0, phase === 2); legend(1, phase === 3); legend(2, phase === 4); legend(3, phase === 5);
    if (phase >= 5) { legend(0, 1); legend(1, 1); legend(2, 1); legend(3, 1); }
    steps.forEach(function (li, i) { li.classList.toggle("on", i === phase); li.classList.toggle("done", i < phase); });
  }

  /* scroll: steps and ring stay in place (CSS sticky) while the wrapper scrolls by */
  var wrap = document.getElementById("reads-wrap"), pin = document.getElementById("reads-pin");
  var topbar = document.querySelector(".topbar"), top = 0;
  var frame = wrap || svg;
  function measure() {
    if (!wrap || !pin) return;
    top = topbar ? Math.round(topbar.getBoundingClientRect().height) : 0;
    document.documentElement.style.setProperty("--reads-top", top + "px");
    document.documentElement.classList.add("reads-live");
    wrap.style.height = (pin.offsetHeight + innerHeight * 1.6) + "px";
  }
  measure(); addEventListener("resize", measure);
  function target() {
    if (!wrap || !pin) { var r0 = svg.getBoundingClientRect(); return clamp(0, 1, (innerHeight * .85 - r0.top) / (r0.height + innerHeight * .3)); }
    var r = wrap.getBoundingClientRect();
    return clamp(0, 1, (top + 12 - r.top) / Math.max(1, r.height - pin.offsetHeight));
  }
  var cur = target(), visible = false, running = false;
  draw(cur);
  function tick() {
    if (!visible) { running = false; return; }
    var t = target();
    cur += (t - cur) * .12; if (Math.abs(t - cur) < .0005) cur = t;
    draw(cur);
    requestAnimationFrame(tick);
  }
  new IntersectionObserver(function (es) {
    visible = es[0].isIntersecting;
    if (visible && !running) { running = true; requestAnimationFrame(tick); }
  }, { rootMargin: "200px" }).observe(frame);
})();
